//! TypeScript types for the React page, generated from the protocol with
//! `ts-rs`. Only with the `ts` feature:
//!
//! - `cargo test -p oxbot-protocol --features ts` checks that the committed
//!   types in `crates/oxbot/ui-src/src/net/protocol/` match the Rust ones.
//! - `cargo test -p oxbot-protocol --features ts -- --ignored export_bindings`
//!   writes them again after a protocol change.
#![cfg(feature = "ts")]
#![allow(clippy::expect_used, reason = "test helpers may panic")]

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use oxbot_protocol::{ClientMsg, ServerMsg};
use ts_rs::TS;

/// Where the page's copy of the types lives.
fn committed_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../oxbot/ui-src/src/net/protocol")
}

/// Writes every type the two messages use (one file each) and an `index.ts`
/// that re-exports them all into `dir`.
fn generate(dir: &Path) {
    ClientMsg::export_all_to(dir).expect("export ClientMsg");
    ServerMsg::export_all_to(dir).expect("export ServerMsg");
    let mut names: Vec<String> = ts_files(dir)
        .into_keys()
        .filter(|name| name != "index.ts")
        .collect();
    names.sort();
    let mut index = String::from(
        "// Generated by crates/oxbot-protocol/tests/bindings.rs. Do not edit this file manually.\n",
    );
    for name in names {
        let ty = name.trim_end_matches(".ts");
        writeln!(index, "export type {{ {ty} }} from \"./{ty}\";").expect("write to a String");
    }
    std::fs::write(dir.join("index.ts"), index).expect("write index.ts");
}

/// The `.ts` files in `dir`, by name.
fn ts_files(dir: &Path) -> BTreeMap<String, String> {
    let Ok(entries) = std::fs::read_dir(dir) else {
        return BTreeMap::new();
    };
    entries
        .map(|entry| entry.expect("read the folder").path())
        .filter(|path| path.extension().is_some_and(|ext| ext == "ts"))
        .map(|path| {
            let name = path
                .file_name()
                .expect("a file name")
                .to_string_lossy()
                .into_owned();
            (
                name,
                std::fs::read_to_string(&path).expect("read a .ts file"),
            )
        })
        .collect()
}

#[test]
fn bindings_up_to_date() {
    let fresh = tempfile::tempdir().expect("a temp folder");
    generate(fresh.path());
    let want = ts_files(fresh.path());
    let have = ts_files(&committed_dir());
    let stale: Vec<&String> = want
        .iter()
        .filter(|(name, text)| have.get(*name) != Some(text))
        .map(|(name, _)| name)
        .chain(have.keys().filter(|name| !want.contains_key(*name)))
        .collect();
    assert!(
        stale.is_empty(),
        "the page's protocol types are out of date ({stale:?}); run \
         `cargo test -p oxbot-protocol --features ts -- --ignored export_bindings`"
    );
}

#[test]
#[ignore = "writes into the source tree; run after a protocol change"]
fn export_bindings() {
    let dir = committed_dir();
    std::fs::create_dir_all(&dir).expect("make the folder");
    for name in ts_files(&dir).keys() {
        std::fs::remove_file(dir.join(name)).expect("remove an old file");
    }
    generate(&dir);
}
